async def send_password_reset_email(email, name, reset_link):

    print("===== SEND PASSWORD RESET EMAIL =====")
    print("To:", email)
    print("Link:", reset_link)

    message = MessageSchema(
        subject="Reset Your JobConnect Password",
        recipients=[email],
        body=f"""
Dear {name},

We received a request to reset your JobConnect password.

Please click the link below to create a new password:

{reset_link}

This password reset link is securely generated by our authentication service and will expire automatically.

If you did not request a password reset, you can safely ignore this email. Your password will remain unchanged.

Regards,

JobConnect Team
""",
        subtype=MessageType.plain,
    )

    fm = FastMail(conf)

    try:
        await fm.send_message(message)
        print("Email sent successfully")
    except Exception as e:
        print("FastMail Error:", type(e))
        print("FastMail Error:", repr(e))


async def send_interview_acceptance_email(
    email: str,
    candidate_name: str,
    position: str,
    company_name: str,
    date: str,
    time: str,
    meeting_link: str,
):
    """
    Send interview acceptance confirmation email to the candidate.
    """
    # Check if we're in test mode
    if os.getenv("PYTEST_CURRENT_TEST"):
        # Set the mock for testing
        email_mock["sent"] = True
        email_mock["email"] = email
        email_mock["candidate"] = candidate_name
        email_mock["company"] = company_name
        email_mock["interview"] = {
            "position": position,
            "date": date,
            "time": time,
            "meeting_link": meeting_link,
        }
        print(f"✅ EMAIL MOCK SET: {email_mock}")
        return

    # Send real email (only when not in test mode)
    message = MessageSchema(
        subject=f"Interview Accepted - {company_name}",
        recipients=[NameEmail(name=candidate_name, email=email)],
        body=f"""

Dear {candidate_name},

Congratulations! You have successfully accepted the interview with {company_name}.

Interview Details:
- Position: {position}
- Date: {date}
- Time: {time}
- Meeting Link: {meeting_link}

What happens next?
- The employer has been notified of your acceptance
- You will receive a reminder before the interview
- Please make sure to join the interview on time

Best regards,
JobConnect Team

""",
        subtype=MessageType.plain,
    )

    fm = FastMail(conf)
    await fm.send_message(message)
